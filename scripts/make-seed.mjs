// One-time import: turns public/products.json + src/config.js into supabase/seed.sql.
//   node scripts/make-seed.mjs
// Then paste supabase/seed.sql into the Supabase SQL editor and run it.
// Re-running the SQL is safe: it skips products and settings that already exist,
// so it never overwrites changes made in the admin dashboard.
import { readFileSync, writeFileSync } from 'node:fs';
import { business, delivery, paymentMethods } from '../src/config.js';

const root = new URL('..', import.meta.url);
const data = JSON.parse(readFileSync(new URL('public/products.json', root), 'utf8'));
const list = Array.isArray(data) ? data : data.products;

const blank = (v) => (v == null ? '' : String(v));
const price = (v) => {
  const n = Number(String(v ?? '').replace(/[^0-9.]/g, ''));
  return Number.isFinite(n) && n > 0 ? n : null;
};
const puffs = (v) => {
  const n = Number(String(v ?? '').replace(/[^0-9]/g, ''));
  return Number.isFinite(n) && n > 0 ? n : null;
};

const products = list.map((p, i) => ({
  id: p.id,
  name: p.name,
  brand: blank(p.brand),
  category: blank(p.category ?? p.type),
  description: blank(p.description),
  price: price(p.price ?? p.price_usd),
  puffs: puffs(p.puffs),
  nicotine: blank(p.nicotine),
  flavours: (p.flavours ?? p.flavors ?? []).map((f) => {
    if (typeof f === 'string') f = { name: f };
    const stock = String(f.inStock ?? f.stock ?? 'available').toLowerCase();
    return {
      name: f.name,
      nicotine: f.nicotine ?? null, // null = use the product's nicotine
      available: !['out', 'out of stock', 'sold out', '0', 'false'].includes(stock),
    };
  }),
  image: blank(p.image),
  hero_image: p.heroImage ?? null,
  in_stock: true,
  active: true,
  featured: Boolean(p.featured),
  is_new: Boolean(p.new ?? p.isNew),
  sort_order: (i + 1) * 10,
}));
const notes = list.filter((p) => p.notes).map((p) => ({ product_id: p.id, notes: p.notes }));

const settings = {
  business: {
    tagline: business.tagline,
    whatsappDisplay: business.whatsappDisplay,
    whatsappNumber: business.whatsappNumber,
    instagramHandle: business.instagramHandle,
    instagramUrl: business.instagramUrl,
  },
  delivery,
  payment_methods: paymentMethods.map((m) => ({ ...m, confirmed: false })),
};

const json = (v) => {
  const s = JSON.stringify(v, null, 2);
  if (s.includes('$seed$')) throw new Error('Unexpected $seed$ in data');
  return `$seed$${s}$seed$::jsonb`;
};

const sql = `-- Generated by scripts/make-seed.mjs from public/products.json and src/config.js.
-- One-time import of the current catalogue and settings. Safe to re-run: existing rows are left alone.

insert into public.products
  (id, name, brand, category, description, price, puffs, nicotine, flavours, image, hero_image,
   in_stock, active, featured, is_new, sort_order)
select id, name, brand, category, description, price, puffs, nicotine, flavours, image, hero_image,
       in_stock, active, featured, is_new, sort_order
from jsonb_to_recordset(${json(products)}) as x(
  id text, name text, brand text, category text, description text, price numeric, puffs integer,
  nicotine text, flavours jsonb, image text, hero_image text, in_stock boolean, active boolean,
  featured boolean, is_new boolean, sort_order integer)
on conflict (id) do nothing;

insert into public.product_notes (product_id, notes)
select product_id, notes from jsonb_to_recordset(${json(notes)}) as x(product_id text, notes text)
on conflict (product_id) do nothing;

insert into public.site_settings (id, business, delivery, payment_methods)
values (1, ${json(settings.business)}, ${json(settings.delivery)}, ${json(settings.payment_methods)})
on conflict (id) do nothing;
`;

writeFileSync(new URL('supabase/seed.sql', root), sql);
console.log(`Wrote supabase/seed.sql: ${products.length} products, ${notes.length} notes, 1 settings row.`);
